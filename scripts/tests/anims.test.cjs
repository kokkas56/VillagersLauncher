// «Анимации»: встроенная библиотека без ошибок, поза и плавность считаются как задумано, файл → чистка → тот же файл.
require('../sync-anims.cjs');
const M = require('../../electron/studio-anim-core.cjs');
let n = 0;
const ok = (c, msg) => { if (!c) { console.error('✗ ' + msg); process.exit(1); } n++; console.log('✓ ' + msg); };
const near = (a, b, e = 1e-3) => Math.abs(a - b) < e;
ok(M.ANIM_LIBRARY.length >= 25, 'встроенных анимаций ' + M.ANIM_LIBRARY.length + ' (нужно 25+)');
ok(M.ANIM_LIBRARY.every((a) => !M.validateAnim(a).some((p) => p.sev === M.ANIM_ERR)), 'встроенные — без ошибок');
ok(new Set(M.ANIM_LIBRARY.map((a) => a.id)).size === M.ANIM_LIBRARY.length, 'id встроенных не повторяются');
ok(['linear', 'smooth', 'in', 'out', 'back', 'bounce', 'step', 'bezier'].every((e) => near(M.ease(e, 0), 0) && near(M.ease(e, 1), 1)), 'плавности: 0 → 0, 1 → 1');
ok(near(M.ease('smooth', 0.5), 0.5) && M.ease('in', 0.5) < 0.2 && M.ease('out', 0.5) > 0.8 && M.ease('back', 0.8) > 1, 'плавности: форма кривых');
const e = M.eulerZYX(M.rotZYX(0.4, -0.7, 1.1));
ok(near(e[0], 0.4) && near(e[1], -0.7) && near(e[2], 1.1), 'углы ZYX ↔ матрица');
const rig = M.playerRig(false);
const bow = M.ANIM_LIBRARY.find((a) => a.id === 'bow');
const s = M.solvePose(rig, bow, 10);
ok(s.bones.head.P[2] < -5 && s.bones.head.P[1] > 2, 'поклон: голова уходит вперёд и вниз (туловище от пояса несёт голову)');
ok(near(s.bones.right_leg.P[1], 12) && near(s.bones.right_leg.P[2], 0), 'поклон: ноги на месте');
const sleep = M.ANIM_LIBRARY.find((a) => a.id === 'sleep');
const sl = M.solvePose(rig, sleep, 5);
ok(sl.bones.head.P[1] > 18, 'сон: всё тело лежит (голова у земли)');
const a2 = M.normalizeAnim(JSON.parse(JSON.stringify(M.cleanAnim(bow))));
ok(JSON.stringify(M.cleanAnim(a2)) === JSON.stringify(M.cleanAnim(bow)), 'файл: чистка устойчива');
const w = M.ANIM_LIBRARY.find((a) => a.id === 'wave');
const v = M.animValues(w, 7);
ok(v.right_arm && near(v.right_arm.rot[2], 152), 'помахать: в 7 т рука поднята (Z 152°)');
const vil = M.villagerRig();
const sv = M.solvePose(vil, w, 7);
ok(sv.freeArms && sv.bones.arms.visible === false && sv.bones.right_arm.visible, 'житель: руки раскрещиваются, если анимация двигает руку');
const m = M.mirrorTracks(w.tracks);
ok(m.left_arm && near(m.left_arm.rot[1].v[2], -152), 'отражение: правая рука → левая, Z с обратным знаком');

// свои кости: группа, предмет, кубик
const withBones = (bones, tracks) => M.normalizeAnim({ id: 'tb', name: 'тест', length: 20, tracks: tracks || {}, bones });
const upper = { id: 'x_upper', name: 'Верх тела', kind: 'group', parent: 'root', pivot: [0, 12, 0], children: ['head', 'right_arm', 'left_arm'] };
const ga = withBones([upper], { x_upper: { rot: [{ t: 0, v: [90, 0, 0] }] } });
const gs = M.solvePose(rig, ga, 0);
ok(near(gs.bones.head.P[0], 0) && near(gs.bones.head.P[1], 12) && near(gs.bones.head.P[2], -12), 'группа: поворот X 90° вокруг пояса уносит голову вперёд (0, 12, −12)');
ok(near(gs.bones.right_leg.P[1], 12) && near(gs.bones.body.P[1], 0), 'группа: кости вне группы на месте');
ok(gs.bones.x_upper && near(gs.bones.x_upper.P[1], 12), 'группа: своя кость в позе (опора на поясе)');
const g0 = M.solvePose(rig, withBones([upper]), 0), p0 = M.solvePose(rig, null, 0);
ok(['head', 'right_arm', 'left_arm'].every((b) => g0.bones[b].P.every((x, i) => near(x, p0.bones[b].P[i]))), 'группа без ключей ничего не двигает');
const lower = { id: 'x_low', name: 'Низ', kind: 'group', parent: 'root', pivot: [0, 12, 0], children: ['body'] };
const bs = M.solvePose(rig, withBones([lower], { x_low: { pos: [{ t: 0, v: [0, -4, 0] }] } }), 0);
ok(near(bs.bones.head.P[1], -4) && near(bs.bones.right_leg.P[1], 12), 'группа с туловищем несёт голову и руки (как наклон туловища), ноги на месте');
const sword = { id: 'x_sword', name: 'Меч', kind: 'item', parent: 'right_arm', pivot: [-1, 10, -2], item: 'minecraft:iron_sword', display: 'hand' };
const box = { id: 'x_box', name: 'Коробка', kind: 'cube', parent: 'x_upper', pivot: [0, 0, -6], from: [-2, -2, -2], size: [4, 4, 4], color: '#c08040' };
const is = M.solvePose(rig, withBones([upper, sword, box], { x_sword: { rot: [{ t: 0, v: [0, 0, 0] }] } }), 0);
ok(near(is.bones.x_sword.P[0], -6) && near(is.bones.x_sword.P[1], 12) && near(is.bones.x_sword.P[2], -2), 'предмет висит на правой руке (опора −6, 12, −2)');
ok(is.bones.x_box && near(is.bones.x_box.P[2], -6) && near(is.bones.x_box.P[1], 12), 'кубик висит на группе');
const good = withBones([upper, sword, box]);
ok(!M.validateAnim(good).some((p) => p.sev === M.ANIM_ERR), 'свои кости: правильный файл без ошибок');
const errOf = (bones) => M.validateAnim(withBones(bones)).filter((p) => p.sev === M.ANIM_ERR).map((p) => p.msg).join(' | ');
ok(/двух группах/.test(errOf([upper, { ...upper, id: 'x_up2', name: 'Вторая', children: ['head'] }])), 'проверка: кость в двух группах');
ok(/не найден/.test(errOf([{ ...sword, parent: 'tail_99x' }])), 'проверка: неизвестный родитель');
ok(/круг/.test(errOf([{ ...upper, parent: 'x_b', children: [] }, { id: 'x_b', name: 'Б', kind: 'group', parent: 'x_upper' }])), 'проверка: кости замкнуты в круг');
ok(/minecraft:iron_sword/.test(errOf([{ ...sword, item: 'Iron Sword' }])), 'проверка: плохой id предмета');
ok(/не больше 16/.test(errOf(Array.from({ length: 17 }, (_, i) => ({ ...box, id: 'x_b' + i, parent: 'body' })))), 'проверка: не больше 16 своих костей');
ok(/кости тела в неё класть нельзя/.test(errOf([{ ...upper, parent: 'right_arm' }])), 'проверка: группа на руке не берёт кости тела');
const c1 = M.cleanAnim(good), c2 = M.cleanAnim(M.normalizeAnim(JSON.parse(JSON.stringify(c1))));
ok(JSON.stringify(c1) === JSON.stringify(c2) && c1.bones.length === 3 && !('bones' in M.cleanAnim(bow)), 'файл со своими костями: чистка устойчива, старые файлы без bones');
const mb = M.mirrorBones(good.bones);
ok(mb[1].parent === 'left_arm' && near(mb[1].pivot[0], 1) && near(mb[2].from[0], -2), 'отражение: предмет переходит в левую руку');
ok(M.boneRu('x_sword', good) === 'Меч' && M.boneRu('x_other') === 'Деталь other', 'имя своей кости');
console.log('\nанимации: ' + n + ' проверок прошло');
