import json, copy, sys

def C(frm, size, slot='base', **kw):
    c = {'from': list(frm), 'size': list(size)}
    if slot != 'base': c['slot'] = slot
    c.update(kw)
    return c

def B(name, parent, pivot, rot=(0, 0, 0), cubes=(), spring=None, **kw):
    b = {'name': name, 'parent': parent, 'pivot': list(pivot), 'rot': list(rot), 'cubes': list(cubes)}
    if spring: b['spring'] = spring
    b.update(kw)
    return b

def S(st, dm, gr, lim, inh=1.0, wind=0.0):
    s = {'stiffness': st, 'damping': dm, 'gravity': gr, 'limit': lim, 'inherit': inh}
    if wind: s['wind'] = wind
    return s

def mirror_cube(c):
    m = copy.deepcopy(c)
    m['from'][0] = -(c['from'][0] + c['size'][0])
    if 'uv' in m: m['mirror'] = not m.get('mirror', False)
    return m

def mirror_bone(b, name, parent=None):
    m = copy.deepcopy(b)
    m['name'] = name
    if parent: m['parent'] = parent
    m['pivot'][0] = -b['pivot'][0]
    m['rot'][1] = -b['rot'][1]
    m['rot'][2] = -b['rot'][2]
    m['cubes'] = [mirror_cube(c) for c in b['cubes']]
    return m

def chain_pair(bones_left, left='_l_', right='_r_'):
    out = list(bones_left)
    for b in bones_left:
        p = b['parent']
        out.append(mirror_bone(b, b['name'].replace(left, right), p.replace(left, right) if left in p else p))
    return out

